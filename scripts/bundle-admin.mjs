import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const pagePath = path.resolve('dist/admin/index.html');
let html = await readFile(pagePath, 'utf8');
const stylesheet = html.match(/<link\s+rel="stylesheet"\s+href="([^"]+\.css)"[^>]*>/i);
if (!stylesheet) throw new Error('Could not find the generated admin stylesheet in dist/admin/index.html');
const stylesheetPath = path.resolve('dist', `.${stylesheet[1]}`);
const css = await readFile(stylesheetPath, 'utf8');
html = html.replace(stylesheet[0], `<style>${css.replace(/<\/style/gi, '<\\/style')}</style>`);
await writeFile(path.resolve('worker/admin-page.ts'), `// Generated by scripts/bundle-admin.mjs; edit src/pages/admin/index.astro instead.\nexport const ADMIN_HTML = ${JSON.stringify(html)};\n`);
process.stdout.write('Bundled the private admin page into worker/admin-page.ts\n');
